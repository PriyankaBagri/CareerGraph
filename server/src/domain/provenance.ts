// Evidence provenance. Three different things are kept apart on purpose:
//   user_provided   - the user typed it in (everything today).
//   system_derived  - CareerGraph itself produced the record or its skill association (nothing produces these yet; the slot exists so it never has to be faked as "user").
//   verified        - an independent party actually checked it. This needs a verification RECORD (who, when, how). There is no verification workflow and no table for
//                     one, so nothing can currently be verified, and no client-supplied field can make evidence "verified".
export type EvidenceOrigin = 'user_provided' | 'system_derived';
export interface VerificationRecord { verifiedBy: string; verifiedAt: string; method: string }
export interface Provenance {
  origin: EvidenceOrigin;
  verification: { status: 'unverified' } | ({ status: 'verified' } & VerificationRecord);
  label: string;
}
interface Source { source: string; verification?: VerificationRecord | null }

const complete = (v: VerificationRecord | null | undefined): v is VerificationRecord => !!v && !!v.verifiedBy?.trim() && !!v.method?.trim() && !Number.isNaN(Date.parse(v.verifiedAt));
export function provenanceOf(e: Source): Provenance {
  const origin: EvidenceOrigin = e.source === 'user' ? 'user_provided' : 'system_derived';
  if (complete(e.verification)) return { origin, verification: { status: 'verified', ...e.verification }, label: `Independently verified by ${e.verification.verifiedBy.trim()} (${e.verification.method.trim()})` };
  return { origin, verification: { status: 'unverified' }, label: origin === 'user_provided' ? 'Self-reported: added by you, not independently verified' : 'Generated by CareerGraph, not independently verified' };
}
