import type { Evidence } from '../types';

// How evidence is labelled in the UI. "Verified" is shown ONLY when the server sent a verified record; everything the user typed is "self-reported".
export interface ProvenanceBadge { text: string; tone: 'ok' | 'warn' | 'neutral'; detail: string }
export function provenanceBadge(e: Pick<Evidence, 'source' | 'provenance'>): ProvenanceBadge {
  if (e.source === 'example') return { text: 'Demo example', tone: 'warn', detail: 'Sample evidence shown for the demo profile. It is not yours and has not been verified.' };
  if (e.provenance?.verification === 'verified') return { text: 'Independently verified', tone: 'ok', detail: e.provenance.label };
  if (e.provenance?.origin === 'system_derived') return { text: 'Generated by CareerGraph', tone: 'neutral', detail: e.provenance.label };
  return { text: 'Self-reported · not verified', tone: 'neutral', detail: e.provenance?.label ?? 'Added by you. Nobody has independently verified it.' };
}
